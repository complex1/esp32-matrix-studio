import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const project = new URL("../", import.meta.url);
const contentTypes = { ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml" };
function discover(folder, prefix = "") {
  return readdirSync(folder, { withFileTypes: true }).flatMap((entry) => {
    const path = `${prefix}${entry.name}`;
    if (entry.isDirectory()) return discover(new URL(`${entry.name}/`, folder), `${path}/`);
    const suffix = path.slice(path.lastIndexOf("."));
    return contentTypes[suffix] && !/\.(?:test|spec)\./.test(path) ? [path] : [];
  }).sort();
}
const assets = discover(new URL("web/", project)).map((path, i) => [`asset${i}`, path]);
let header = "// Generated by node scripts/embed_web.mjs; edit web/ files instead.\n#pragma once\n#include <Arduino.h>\nnamespace Matrix { namespace WebAssets {\n";
let total = 0;
for (const [name, filename] of assets) {
  const bytes = gzipSync(readFileSync(new URL(`web/${filename}`, project)), { level: 9 });
  total += bytes.length;
  header += `const uint8_t ${name}[] PROGMEM = {\n`;
  for (let offset = 0; offset < bytes.length; offset += 20) {
    header += `  ${Array.from(bytes.subarray(offset, offset + 20), (byte) => `0x${byte.toString(16).padStart(2, "0")}`).join(",")},\n`;
  }
  header += "};\n";
}
header += "} }  // namespace Matrix::WebAssets\n";
header = header.replace("} }  // namespace Matrix::WebAssets\n", "struct Asset { const char *path; const char *type; const uint8_t *data; size_t length; };\nconst Asset assets[] = {\n" + assets.map(([name, path]) => `  {\"/${path}\", \"${contentTypes[path.slice(path.lastIndexOf('.'))]}\", ${name}, sizeof(${name})},`).join("\n") + "\n};\n} }  // namespace Matrix::WebAssets\n");
const output = new URL("WebAssets.h", project);
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== header) throw new Error("WebAssets.h is stale; run node scripts/embed_web.mjs");
  console.log("Embedded web assets match web/ sources.");
} else {
  writeFileSync(output, header);
  console.log(`Embedded ${assets.length} assets (${total} gzip bytes) in ${fileURLToPath(output)}`);
}
