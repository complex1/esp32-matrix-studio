import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { gzipSync, gunzipSync } from "node:zlib";

const project = new URL("../", import.meta.url);
const contentTypes = { ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml" };
const preamble = "// Generated by node scripts/embed_web.mjs; edit web/ files instead.\n#pragma once\n#include <Arduino.h>\nnamespace Matrix { namespace WebAssets {\n";
const staleMessage = "WebAssets.h is stale; run node scripts/embed_web.mjs";

function discover(folder, prefix = "") {
  return readdirSync(folder, { withFileTypes: true }).flatMap((entry) => {
    const path = `${prefix}${entry.name}`;
    if (entry.isDirectory()) return discover(new URL(`${entry.name}/`, folder), `${path}/`);
    const suffix = path.slice(path.lastIndexOf("."));
    return contentTypes[suffix] && !/\.(?:test|spec)\./.test(path) ? [path] : [];
  }).sort();
}

export function loadSources(projectURL = project) {
  return discover(new URL("web/", projectURL)).map((path, i) => ({
    name: `asset${i}`,
    path,
    type: contentTypes[path.slice(path.lastIndexOf("."))],
    source: readFileSync(new URL(`web/${path}`, projectURL)),
  }));
}

function table(assets) {
  return "struct Asset { const char *path; const char *type; const uint8_t *data; size_t length; };\nconst Asset assets[] = {\n" +
    assets.map(({ name, path, type }) => `  {\"/${path}\", \"${type}\", ${name}, sizeof(${name})},`).join("\n") +
    "\n};\n} }  // namespace Matrix::WebAssets\n";
}

// Generation retains its existing level-9 gzip and 20-byte C++ formatting.
export function createHeader(assets) {
  let header = preamble;
  let total = 0;
  for (const { name, source } of assets) {
    const bytes = gzipSync(source, { level: 9 });
    total += bytes.length;
    header += `const uint8_t ${name}[] PROGMEM = {\n`;
    for (let offset = 0; offset < bytes.length; offset += 20) {
      header += `  ${Array.from(bytes.subarray(offset, offset + 20), (byte) => `0x${byte.toString(16).padStart(2, "0")}`).join(",")},\n`;
    }
    header += "};\n";
  }
  return { header: header + table(assets), total };
}

// gzip streams can differ across platforms or zlib versions while containing
// identical assets. Validate the exact source bytes and the whole C++ schema,
// rather than requiring a freshly recompressed stream to have identical bytes.
export function verifyEmbeddedHeader(header, assets) {
  if (typeof header !== "string" || !header.startsWith(preamble)) return false;
  let remaining = header.slice(preamble.length);
  for (const { name, source } of assets) {
    const match = /^const uint8_t (asset\d+)\[\] PROGMEM = \{\n([\s\S]*?)\n\};\n/.exec(remaining);
    if (!match || match[1] !== name) return false;
    const tokens = match[2].trim().split(",");
    if (tokens.pop() !== "" || tokens.length === 0 ||
        tokens.some((token) => !/^0x[\da-f]{2}$/i.test(token.trim()))) return false;
    const bytes = Buffer.from(tokens.map((token) => Number.parseInt(token.trim().slice(2), 16)));
    try {
      // Limit decompression to the expected source size so a bad stream cannot
      // inflate unchecked. Empty sources still need a nonzero zlib limit.
      const decoded = gunzipSync(bytes, { maxOutputLength: Math.max(1, source.length) });
      if (!decoded.equals(source)) return false;
    } catch {
      return false;
    }
    remaining = remaining.slice(match[0].length);
  }
  // Exact table equality enforces count, order, URL, MIME, array identity,
  // sizeof reference, struct schema and absence of extra declarations.
  return remaining === table(assets);
}

export function run(projectURL = project, check = process.argv.includes("--check")) {
  const assets = loadSources(projectURL);
  const output = new URL("WebAssets.h", projectURL);
  if (check) {
    let header;
    try { header = readFileSync(output, "utf8"); }
    catch { throw new Error(staleMessage); }
    if (!verifyEmbeddedHeader(header, assets)) throw new Error(staleMessage);
    console.log("Embedded web assets match web/ sources.");
  } else {
    const { header, total } = createHeader(assets);
    writeFileSync(output, header);
    console.log(`Embedded ${assets.length} assets (${total} gzip bytes) in ${fileURLToPath(output)}`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  run();
}
